def alias_name(netloc):
    try:
        return HOST_ALIASES[netloc.lower()]
    except KeyError:
        raise SystemExit("no alias name for {}: add one to HOST_ALIASES (a name for "
                         "the site, not the host name)".format(netloc))


def alias_for(url, aliases, own):
    """`alias:path` for a source URL. `own` is project.conf's aliases: a name
    that is there with the same base is used as it is (and not written again),
    one with another base is an error to be settled by hand."""
    if url.startswith(MIRROR_ALIAS + ":"):
        return url
    parts = urllib.parse.urlparse(url)
    base = served_base("{}://{}/".format(parts.scheme, parts.netloc))
    alias = alias_name(parts.netloc)
    if alias in own:
        if own[alias] != base:
            raise SystemExit("alias {} is {} in project.conf, {} here".format(alias, own[alias], base))
    elif aliases.setdefault(alias, base) != base:
        raise SystemExit("alias {} would be both {} and {}".format(alias, aliases[alias], base))
    path = parts.path.lstrip("/") + ("?" + parts.query if parts.query else "")
    return "{}:{}".format(alias, path)


# Elements ---------------------------------------------------------------


def q(text):
    return json.dumps(text)


def element(kind_lines, depends, sources=(), config=()):
    out = [MARKER, "kind: lbstep\n", "\n"]
    out.append("build-depends:\n")
    out += ["- {}\n".format(d) for d in depends]
    out += ["\n", "variables:\n", "  install-root: /\n", "\n"]
    if sources:
        out.append("sources:\n")
        for fname, sha, url in sources:
            out += [
                "- kind: remote\n",
                "  url: {}\n".format(q(url)),
                "  filename: {}\n".format(q(fname)),
                "  ref: {}\n".format(sha),
                "  directory: external/distfiles\n",
            ]
        out.append("\n")
    out.append("config:\n")
    out += ["  {}\n".format(c) for c in config]
    return "".join(out)


def unique(name, used):
    if name not in used:
        used[name] = 1
        return name
    used[name] += 1
    return "{}-{}".format(name, used[name])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--lb", required=True, help="live-bootstrap checkout")
    ap.add_argument("--project", default=os.path.join(os.path.dirname(__file__), ".."))
    ap.add_argument("--subdir", default="live-bootstrap", help="below elements/")
    ap.add_argument("--stage0", default="stage0.bst")
    ap.add_argument("--mirror", action="append",
                    help="live-bootstrap mirror for the `g` (repackaged git) sources; "
                    "repeat for fallbacks (default: the project's three public mirrors)")
    ap.add_argument("--final-jobs", type=int, default=4,
                    help="JOBS the compile-heavy steps run with (FINAL_JOBS)")
    args = ap.parse_args()

    mirrors = args.mirror or [
        "https://files.bootstrapping.world/",
        "https://samuelt.me/pub/live-bootstrap/",
        "https://live-bootstrap.stikonas.eu/",
    ]
    mirrors = [m.rstrip("/") + "/" for m in mirrors]
    project = os.path.abspath(args.project)
    steps_dir = os.path.join(args.lb, "steps")
    out_dir = os.path.join(project, "elements", args.subdir)
    prefix = args.subdir + "/"

    commit = subprocess.run(["git", "-C", args.lb, "rev-parse", "HEAD"],
                            check=True, capture_output=True, text=True).stdout.strip()
    if subprocess.run(["git", "-C", args.lb, "status", "--porcelain", "--untracked-files=no"],
                      capture_output=True, text=True).stdout.strip():
        print("warning: {} has uncommitted changes, pinning {} anyway".format(args.lb, commit), file=sys.stderr)

    os.makedirs(out_dir, exist_ok=True)
    for fname in os.listdir(out_dir):
        path = os.path.join(out_dir, fname)
        if fname.endswith(".bst") and open(path, encoding="utf-8").readline() == MARKER:
            os.remove(path)

    pins = load_pins(os.path.join(os.path.dirname(os.path.abspath(__file__)), "lb-pinned-checksums.txt"))
    used_pins = set()
    written = {}
    aliases = {}
    own_aliases = project_aliases(project)
    staged = {}
    passes = {}
    used = {}
    skipped = []

    def write(name, text):
        written[name] = text

    write("steps", MARKER + """kind: import

# live-bootstrap's steps/ directory, imported at /steps where the step
# scripts expect to find it.
sources:
- kind: git
  url: github:fosslinux/live-bootstrap
  track: master
  ref: {}

config:
  source: steps
  target: /steps
""".format(commit))

    write("base", MARKER + """kind: lbstep

# Emulates the first half of live-bootstrap's seed/seed.kaem: create the
# directory layout and install the stage0 tools into /usr/bin.
build-depends:
- {stage0}
- {prefix}steps.bst

variables:
  install-root: /

config:
  action: setup
  write-bootstrap-cfg: true
  bootstrap-cfg:
    FINAL_JOBS: {jobs}
  commands:
{commands}""".format(stage0=args.stage0, prefix=prefix, jobs=args.final_jobs, commands=BASE_COMMANDS))

    previous = prefix + "base.bst"

    for directive, arg in parse_manifest(os.path.join(steps_dir, "manifest"), CONFIG):
        if directive == "build":
            pkg = arg
            pass_no = passes[pkg] = passes.get(pkg, 0) + 1
            base = os.path.join(steps_dir, pkg, "pass{}".format(pass_no))
            kaem, sh = os.path.exists(base + ".kaem"), os.path.exists(base + ".sh")
            # No script at all is fine: build() then runs the default stages
            # from the package's sources and mk/ files.
            if kaem and sh:
                raise SystemExit("{}: both {}.kaem and {}.sh exist".format(pkg, base, base))

            sources = []
            for fname, sha, url in parse_sources(os.path.join(steps_dir, pkg, "sources")):
                if staged.setdefault(fname, sha) != sha:
                    raise SystemExit("{}: {} has two different checksums".format(pkg, fname))
                if (fname, sha) in staged_done:
                    continue
                staged_done.add((fname, sha))
                sources.append((fname, sha, alias_for(url, aliases, own_aliases)))

            name = pkg if pass_no == 1 else "{}-pass{}".format(pkg, pass_no)
            config = ["action: build", "pkg: {}".format(pkg), "pass: {}".format(pass_no)]
            # The package file is named after the revision, i.e. how many
            # builds of this package came before (get_revision() in helpers.sh).
            package = "{}_{}.tar.bz2".format(pkg, pass_no - 1)
            if package in pins:
                used_pins.add(package)
                config += ["package-checksums:", "  {}: {}".format(q(package), pins[package])]
            text = element(None, [previous], sources, config)
        elif directive == "improve":
            if arg in SKIPPED_IMPROVES:
                skipped.append((directive, arg, SKIPPED_IMPROVES[arg]))
                continue
            name = unique("improve-" + arg, used)
            config = ["action: improve", "pkg: {}".format(arg)]
            if arg in FILTERED_IMPROVES:
                with open(os.path.join(steps_dir, "improve", arg + ".sh"), encoding="utf-8") as f:
                    body = [l.rstrip("\n") for l in f if not MOUNT_LINES.match(l)]
                config += ["script:"] + ["  - {}".format(q(l)) for l in body]
            text = element(None, [previous], (), config)
        elif directive == "uninstall":
            name = unique("uninstall-" + arg.split()[0], used)
            text = element(None, [previous], (), ["action: uninstall", "pkg: {}".format(q(arg))])
        elif directive == "jump":
            skipped.append((directive, arg, "kernel/disk handover"))
            continue
        else:
            raise SystemExit("unknown directive {!r}".format(directive))

        write(name, text)
        previous = "{}{}.bst".format(prefix, name)

    write("all", MARKER + """kind: stack

# Everything live-bootstrap builds for this configuration.
depends:
- {}
""".format(previous))

    for stale in sorted(set(pins) - used_pins):
        print("warning: pinned checksum for {} matches no element".format(stale), file=sys.stderr)

    for name, text in written.items():
        with open(os.path.join(out_dir, name + ".bst"), "w", encoding="utf-8") as f:
            f.write(text)

    os.makedirs(os.path.join(project, "include"), exist_ok=True)
    with open(os.path.join(project, "include", "lb-aliases.yml"), "w", encoding="utf-8") as f:
        f.write(MARKER + "\naliases:\n")
        for alias, base in sorted(aliases.items()):
            f.write("  {}: {}\n".format(alias, q(base)))
        f.write("  {}: {}\n".format(MIRROR_ALIAS, q(mirrors[0])))
        f.write("\nmirrors:\n- name: live-bootstrap\n  aliases:\n    {}:\n".format(MIRROR_ALIAS))
        for m in mirrors[1:]:
            f.write("    - {}\n".format(q(m)))

    print("{} elements in elements/{}, {} aliases, live-bootstrap {}".format(
        len(written), args.subdir, len(aliases), commit[:8]))
    for directive, arg, why in skipped:
        print("  skipped {}: {} ({})".format(directive, arg, why))


staged_done = set()

if __name__ == "__main__":
    main()
