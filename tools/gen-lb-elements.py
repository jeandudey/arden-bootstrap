#!/usr/bin/env python3
"""
Generate BuildStream elements from live-bootstrap's steps/manifest.

    tools/gen-lb-elements.py --lb PATH/TO/live-bootstrap

One element is written per `build`, `improve` and `uninstall` directive that
applies to a bubblewrap-style (CHROOT) x86 run, chained so that each element
build-depends on the one before it, ending in a `stack` element, `all.bst`.
Kernel, console, network and disk steps are dropped (see SKIPPED_IMPROVES).
Sources become pinned `remote` sources staged in /external/distfiles and
their hosts become aliases in include/lb-aliases.yml.

The checkout is only read; the commit it is at is pinned in steps.bst.
Generated files carry a marker and are removed and rewritten on each run.
"""

import argparse
import json
import os
import posixpath
import re
import subprocess
import sys
import urllib.parse

MIRROR_ALIAS = "lb-mirror"

# live-bootstrap lists some sources with http:// URLs although their hosts serve
# them over https (the sha256 pins protect the contents either way, but plain
# http lets anyone on the path see and break the download). The alias's base
# is written as https for these; the alias names stay as they were derived from
# the listed URL, since the element files carry them (and a changed name would
# change the cache key of every element that uses it). ftp.astron.com and
# ftp.unicode.org have no https.
HTTPS_HOSTS = {
    "downloads.sourceforge.net",
    "libarchive.org",
    "mirrors.kernel.org",
    "www.cpan.org",
}


def served_base(base):
    """The alias value to write for the base URL taken from live-bootstrap."""
    parts = urllib.parse.urlparse(base)
    if parts.scheme == "http" and parts.netloc in HTTPS_HOSTS:
        return "https://{}/".format(parts.netloc)
    return base

MARKER = "# Generated by tools/gen-lb-elements.py, do not edit.\n"

# The configuration the generated elements run with, as seen by manifest
# predicates. It mirrors plugins/lbstep.py's BOOTSTRAP_CFG.
CONFIG = {
    "ARCH": "x86",
    "ARCH_DIR": "x86",
    "FORCE_TIMESTAMPS": "False",
    "CHROOT": "True",
    "UPDATE_CHECKSUMS": "False",
    "INTERNAL_CI": "False",
    "INTERACTIVE": "False",
    "KERNEL_BOOTSTRAP": "False",
    "BUILD_KERNELS": "False",
    "CONFIGURATOR": "False",
    "SWAP_SIZE": "0",
}

# improve steps that make no sense inside a BuildStream sandbox.
SKIPPED_IMPROVES = {
    "reconfigure": "regenerates live-bootstrap's own scripts",
    "populate_device_nodes": "mknod/mount; the sandbox provides /dev",
    "cleanup_filesystem": "only saves space",
    "after": "interactive shell and shutdown",
    "open_console": "interactive",
    "swap": "needs a real machine",
    "get_network": "needs a real machine",
    "make_bootable": "needs a real machine",
    "null_time": "timestamps are normalised by the artifact",
    "update_checksums": "only for regenerating checksums",
}

# improve steps run with some lines removed: mounting filesystems cannot work
# in a sandbox, where /proc, /dev and /tmp are already provided. Everything else
# in the script is kept, notably /etc/passwd, which Perl's Configure reads (via
# whoami) to record who built it.
MOUNT_LINES = re.compile(r"^\s*(mount\b|rm /junk\b)")
FILTERED_IMPROVES = {"finalize_fhs"}

BASE_COMMANDS = """\
  # stage0's cp drops the executable bit, so copy using the originals only
  - PATH=/${ARCH_DIR}/bin
  - mkdir -p ${PREFIX} ${BINDIR} ${LIBDIR} ${INCDIR} ${SRCDIR} ${TMPDIR} /dev
""" + "".join(
    "  - cp /${{ARCH_DIR}}/bin/{0} ${{BINDIR}}/{0}\n".format(t)
    for t in (
        "blood-elf catm chmod cp get_machine hex2 kaem match M1 M2-Mesoplanet "
        "M2-Planet mkdir replace rm sha256sum unbz2 ungz untar unxz"
    ).split()
) + """\
  - chmod 755 ${BINDIR}/blood-elf ${BINDIR}/catm ${BINDIR}/chmod ${BINDIR}/cp
  - chmod 755 ${BINDIR}/get_machine ${BINDIR}/hex2 ${BINDIR}/kaem ${BINDIR}/match
  - chmod 755 ${BINDIR}/M1 ${BINDIR}/M2-Mesoplanet ${BINDIR}/M2-Planet ${BINDIR}/mkdir
  - chmod 755 ${BINDIR}/replace ${BINDIR}/rm ${BINDIR}/sha256sum ${BINDIR}/unbz2
  - chmod 755 ${BINDIR}/ungz ${BINDIR}/untar ${BINDIR}/unxz
  - PATH=${BINDIR}:/${ARCH_DIR}/bin
"""


class Step:
    def __init__(self, action, pkg, name, pass_no=None, sources=()):
        self.action = action
        self.pkg = pkg
        self.name = name
        self.pass_no = pass_no
        self.sources = list(sources)


# Manifest ---------------------------------------------------------------


def tokenize(expr):
    return re.findall(r"\(|\)|==|!=|\|\||&&|[^\s()=!|&]+", expr)


def evaluate(tokens, config):
    """Evaluate `( A == b || C != d && E )`; the tokens include the parens."""

    def value(name):
        return config.get(name, "")

    def atom(pos):
        if tokens[pos] == "(":
            result, pos = disjunction(pos + 1)
            if tokens[pos] != ")":
                raise ValueError("expected ')' in {}".format(tokens))
            return result, pos + 1
        name = tokens[pos]
        if pos + 1 < len(tokens) and tokens[pos + 1] in ("==", "!="):
            rhs = tokens[pos + 2]
            equal = value(name) == rhs
            return (equal if tokens[pos + 1] == "==" else not equal), pos + 3
        return value(name) == "True", pos + 1

    def conjunction(pos):
        result, pos = atom(pos)
        while pos < len(tokens) and tokens[pos] == "&&":
            rhs, pos = atom(pos + 1)
            result = result and rhs
        return result, pos

    def disjunction(pos):
        result, pos = conjunction(pos)
        while pos < len(tokens) and tokens[pos] == "||":
            rhs, pos = conjunction(pos + 1)
            result = result or rhs
        return result, pos

    result, pos = disjunction(0)
    if pos != len(tokens):
        raise ValueError("trailing tokens in {}".format(tokens))
    return result


def split_predicate(rest):
    """Split `args ( predicate )` into (args, predicate tokens or None)."""
    idx = rest.find(" ( ")
    if idx < 0 or not rest.rstrip().endswith(")"):
        return rest.strip(), None
    return rest[:idx].strip(), tokenize(rest[idx:])


def parse_manifest(path, config):
    """Yield (directive, args) for the directives that apply."""
    config = dict(config)
    with open(path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.split(" #", 1)[0].strip() if not line.startswith("#") else ""
            if not line:
                continue
            directive, _, rest = line.partition(":")
            rest = rest.strip()
            if directive == "define":
                name, _, rhs = rest.partition("=")
                name, rhs = name.strip(), rhs.strip()
                if rhs.startswith("("):
                    config[name] = "True" if evaluate(tokenize(rhs), config) else "False"
                else:
                    args, pred = split_predicate(rhs)
                    if pred is None or evaluate(pred, config):
                        config[name] = args
                continue
            args, pred = split_predicate(rest)
            if pred is not None and not evaluate(pred, config):
                continue
            yield directive, args


# Sources ----------------------------------------------------------------


def parse_sources(path):
    """Return [(filename, sha256, url)] for a step's sources file."""
    found = {}
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split()
            if not fields:
                continue
            is_git = fields[0] == "g"
            if is_git:
                # `g repo~rev url sha256 [name]`: a git checkout repackaged
                # as a tarball. source_line_action() drops the repo~rev.
                fields = fields[1:]
            elif fields[0] != "f":
                raise ValueError("{}: unknown source line {!r}".format(path, line))
            url, sha = fields[1], fields[2]
            fname = fields[3] if len(fields) > 3 else posixpath.basename(urllib.parse.urlparse(url).path)
            if is_git or url == "_":
                # Repackaged checkouts are only reliably available from the
                # live-bootstrap mirrors (cgit and GitHub snapshots are not
                # stable); BuildStream falls back through `mirrors:`.
                url = "{}:{}".format(MIRROR_ALIAS, fname)
            # The first listed URL for a given file wins; the rest are mirrors.
            found.setdefault((fname, sha), url)
    return [(fname, sha, url) for (fname, sha), url in found.items()]


def load_pins(path):
    """{package file: sha256} from tools/lb-pinned-checksums.txt."""
    pins = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.split("#", 1)[0].split()
                if line:
                    pins[line[1]] = line[0]
    return pins


def project_aliases(project):
    """{name: base} of the aliases project.conf defines itself."""
    found = {}
    with open(os.path.join(project, "project.conf"), encoding="utf-8") as f:
        inside = False
        for line in f:
            if line.startswith("aliases:"):
                inside = True
            elif inside and re.match(r"^\S", line):
                break
            elif inside:
                m = re.match(r"^  ([\w-]+):\s+(\S+)\s*$", line)
                if m:
                    found[m[1]] = m[2]
    return found


# The names of the hosts' aliases. An alias names what the site is (the
